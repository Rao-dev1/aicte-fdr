"""Storage for uploaded FDR documents.

- If R2_BUCKET is set, files go to Cloudflare R2 (cloud storage). This is used when the app is online.
- Otherwise files go to a local folder (UPLOAD_DIR). This is used on your own computer.

Keys are generated by the server (uuid + extension), never taken from the client.
"""

import os
from pathlib import Path
from typing import Optional


def upload_dir() -> Path:
    return Path(os.getenv("UPLOAD_DIR", "./uploads"))


def _r2_bucket() -> Optional[str]:
    return os.getenv("R2_BUCKET") or None


def _r2_client():
    import boto3

    account_id = os.environ["R2_ACCOUNT_ID"]
    return boto3.client(
        "s3",
        endpoint_url=f"https://{account_id}.r2.cloudflarestorage.com",
        aws_access_key_id=os.environ["R2_ACCESS_KEY_ID"],
        aws_secret_access_key=os.environ["R2_SECRET_ACCESS_KEY"],
        region_name="auto",
    )


def save(key: str, data: bytes) -> None:
    bucket = _r2_bucket()
    if bucket:
        _r2_client().put_object(Bucket=bucket, Key=key, Body=data)
        return
    folder = upload_dir()
    folder.mkdir(parents=True, exist_ok=True)
    (folder / key).write_bytes(data)


def read(key: str) -> Optional[bytes]:
    """Returns the file contents, or None if the file is missing."""
    bucket = _r2_bucket()
    if bucket:
        from botocore.exceptions import ClientError

        try:
            return _r2_client().get_object(Bucket=bucket, Key=key)["Body"].read()
        except ClientError:
            return None
    path = upload_dir() / key
    return path.read_bytes() if path.exists() else None
