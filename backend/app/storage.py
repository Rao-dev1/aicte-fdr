"""Storage for uploaded FDR documents.

- If S3_BUCKET is set (or R2_BUCKET for Cloudflare R2), files go to an S3-compatible bucket.
  Backblaze B2 is the free option used here. Set S3_ENDPOINT_URL, S3_REGION, S3_KEY_ID and S3_APPLICATION_KEY.
- Otherwise files go to a local folder (UPLOAD_DIR). This is used on your own computer.

Keys are generated by the server (uuid + extension), never taken from the client.
"""

import os
from pathlib import Path
from typing import Optional


def upload_dir() -> Path:
    return Path(os.getenv("UPLOAD_DIR", "./uploads"))


def _bucket() -> Optional[str]:
    return os.getenv("S3_BUCKET") or os.getenv("R2_BUCKET") or None


def _client():
    import boto3

    endpoint = os.getenv("S3_ENDPOINT_URL")
    if not endpoint:  # older Cloudflare R2 settings
        endpoint = f"https://{os.environ['R2_ACCOUNT_ID']}.r2.cloudflarestorage.com"
    key_id = os.getenv("S3_KEY_ID") or os.environ["R2_ACCESS_KEY_ID"]
    secret = os.getenv("S3_APPLICATION_KEY") or os.environ["R2_SECRET_ACCESS_KEY"]
    return boto3.client(
        "s3",
        endpoint_url=endpoint,
        aws_access_key_id=key_id,
        aws_secret_access_key=secret,
        region_name=os.getenv("S3_REGION", "auto"),
    )


def save(key: str, data: bytes) -> None:
    bucket = _bucket()
    if bucket:
        _client().put_object(Bucket=bucket, Key=key, Body=data)
        return
    folder = upload_dir()
    folder.mkdir(parents=True, exist_ok=True)
    (folder / key).write_bytes(data)


def read(key: str) -> Optional[bytes]:
    """Returns the file contents, or None if the file is missing."""
    bucket = _bucket()
    if bucket:
        from botocore.exceptions import ClientError

        try:
            return _client().get_object(Bucket=bucket, Key=key)["Body"].read()
        except ClientError:
            return None
    path = upload_dir() / key
    return path.read_bytes() if path.exists() else None
